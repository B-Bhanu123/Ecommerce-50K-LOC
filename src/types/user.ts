export type UserID = string | number;
export type UserStatus = 'active' | 'inactive' | 'pending' | 'archived' | 'deleted' | 'processing' | 'completed' | 'failed';
export type UserPriority = 'low' | 'medium' | 'high' | 'critical';

export interface IUserBaseConfig {
  id: UserID;
  code: string;
  name: string;
  slug: string;
  description?: string;
  status: UserStatus;
  priority: UserPriority;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date | null;
  version: number;
  metadata: Record<string, any>;
}

export interface IUserPayload extends Omit<IUserBaseConfig, 'id' | 'createdAt' | 'updatedAt' | 'version'> {
  attributes: Record<string, string | number | boolean>;
  tags: string[];
  isSystemManaged: boolean;
  customFlags: Map<string, boolean>;
}

