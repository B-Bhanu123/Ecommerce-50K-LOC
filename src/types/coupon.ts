export type CouponID = string | number;
export type CouponStatus = 'active' | 'inactive' | 'pending' | 'archived' | 'deleted' | 'processing' | 'completed' | 'failed';
export type CouponPriority = 'low' | 'medium' | 'high' | 'critical';

export interface ICouponBaseConfig {
  id: CouponID;
  code: string;
  name: string;
  slug: string;
  description?: string;
  status: CouponStatus;
  priority: CouponPriority;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date | null;
  version: number;
  metadata: Record<string, any>;
}

export interface ICouponPayload extends Omit<ICouponBaseConfig, 'id' | 'createdAt' | 'updatedAt' | 'version'> {
  attributes: Record<string, string | number | boolean>;
  tags: string[];
  isSystemManaged: boolean;
  customFlags: Map<string, boolean>;
}

