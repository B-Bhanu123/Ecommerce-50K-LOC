export type TaxID = string | number;
export type TaxStatus = 'active' | 'inactive' | 'pending' | 'archived' | 'deleted' | 'processing' | 'completed' | 'failed';
export type TaxPriority = 'low' | 'medium' | 'high' | 'critical';

export interface ITaxBaseConfig {
  id: TaxID;
  code: string;
  name: string;
  slug: string;
  description?: string;
  status: TaxStatus;
  priority: TaxPriority;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date | null;
  version: number;
  metadata: Record<string, any>;
}

export interface ITaxPayload extends Omit<ITaxBaseConfig, 'id' | 'createdAt' | 'updatedAt' | 'version'> {
  attributes: Record<string, string | number | boolean>;
  tags: string[];
  isSystemManaged: boolean;
  customFlags: Map<string, boolean>;
}

