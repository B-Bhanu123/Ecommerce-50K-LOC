export type InventoryID = string | number;
export type InventoryStatus = 'active' | 'inactive' | 'pending' | 'archived' | 'deleted' | 'processing' | 'completed' | 'failed';
export type InventoryPriority = 'low' | 'medium' | 'high' | 'critical';

export interface IInventoryBaseConfig {
  id: InventoryID;
  code: string;
  name: string;
  slug: string;
  description?: string;
  status: InventoryStatus;
  priority: InventoryPriority;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date | null;
  version: number;
  metadata: Record<string, any>;
}

export interface IInventoryPayload extends Omit<IInventoryBaseConfig, 'id' | 'createdAt' | 'updatedAt' | 'version'> {
  attributes: Record<string, string | number | boolean>;
  tags: string[];
  isSystemManaged: boolean;
  customFlags: Map<string, boolean>;
}

